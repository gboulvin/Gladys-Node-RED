// -----------------------------------------------------------------------------
// Generator of the Node-RED `settings.js`.
//
// The Node-RED sub-container mounts its `/data` user directory from
// `/data/containers/node-red/data` of the integration: the integration writes
// the settings file there before starting it, and restarts Node-RED when the
// file changes. The file is rewritten at every start: the source of truth is
// the integration configuration in Gladys, never a hand edit.
//
// What the generated settings do:
//   - protect the editor and the admin API (adminAuth) with the credentials of
//     the configuration. The password is stored as a scrypt hash (Node's
//     built-in crypto: no bcrypt to install in the Node-RED image);
//   - optionally protect the HTTP endpoints of the flows (`http in` nodes)
//     with the same credentials, through httpNodeMiddleware;
//   - expose the Gladys event endpoint to the flows: the GLADYS_EVENT_URL and
//     GLADYS_EVENT_TOKEN environment variables, and a `gladys.trigger()`
//     helper in the global context of the function nodes;
//   - enable runtimeState, so the flows can be stopped and started from Gladys.
//
// Every value is injected with JSON.stringify: the configuration can never
// inject code into the file.
// -----------------------------------------------------------------------------

import { scryptSync } from 'node:crypto';

export const SCRYPT_KEY_LENGTH = 32;

/**
 * scrypt hash of the admin password, with Node's default cost parameters
 * (the ones `crypto.scryptSync` uses inside Node-RED when it checks a login).
 */
export function hashPassword(password, saltHex) {
  return scryptSync(password, Buffer.from(saltHex, 'hex'), SCRYPT_KEY_LENGTH).toString('hex');
}

/**
 * Build the content of settings.js.
 * @param {object} options
 * @param {object} options.config normalized integration config
 * @param {object} options.secrets see src/secrets.js
 * @param {string} options.eventUrl URL of the integration event endpoint
 */
export function buildSettings({ config, secrets, eventUrl }) {
  const values = {
    ADMIN_USERNAME: config.username,
    PASSWORD_SALT: secrets.password_salt,
    PASSWORD_HASH: hashPassword(config.password, secrets.password_salt),
    CREDENTIAL_SECRET: secrets.credential_secret,
    PROTECT_HTTP_NODES: config.protect_http_nodes,
    PERSIST_CONTEXT: config.persist_context,
    GLADYS_EVENT_URL: eventUrl,
    GLADYS_EVENT_TOKEN: secrets.event_token,
  };
  const constants = Object.entries(values)
    .map(([name, value]) => `const ${name} = ${JSON.stringify(value)};`)
    .join('\n');

  return `${HEADER}
${constants}
${BODY}`;
}

const HEADER = `/**
 * Node-RED settings — GENERATED by the Gladys Node-RED integration.
 *
 * This file is rewritten every time the integration starts: change the
 * configuration of the integration in Gladys instead of editing it.
 * Documentation: https://nodered.org/docs/user-guide/runtime/configuration
 */
'use strict';

const crypto = require('crypto');
`;

const BODY = `
// Flows reach the Gladys event endpoint with these variables, e.g. in an
// "http request" node: URL \${GLADYS_EVENT_URL}, header
// "Authorization: Bearer \${GLADYS_EVENT_TOKEN}".
process.env.GLADYS_EVENT_URL = GLADYS_EVENT_URL;
process.env.GLADYS_EVENT_TOKEN = GLADYS_EVENT_TOKEN;

function sha256(text) {
  return crypto.createHash('sha256').update(String(text)).digest();
}

function checkCredentials(username, password) {
  if (typeof username !== 'string' || typeof password !== 'string') {
    return false;
  }
  const expected = Buffer.from(PASSWORD_HASH, 'hex');
  const actual = crypto.scryptSync(password, Buffer.from(PASSWORD_SALT, 'hex'), expected.length);
  // Both comparisons always run: no early exit telling which one failed.
  const sameUser = crypto.timingSafeEqual(sha256(username), sha256(ADMIN_USERNAME));
  const samePassword = crypto.timingSafeEqual(actual, expected);
  return sameUser && samePassword;
}

// scrypt is deliberately slow: remember the last Basic headers that were
// accepted (as hashes) so a busy HTTP endpoint does not pay it on every call.
const acceptedHeaders = new Set();
function checkBasicHeader(header) {
  const match = /^Basic\\s+(.+)$/i.exec(header || '');
  if (!match) {
    return false;
  }
  const key = sha256(match[1]).toString('hex');
  if (acceptedHeaders.has(key)) {
    return true;
  }
  const decoded = Buffer.from(match[1], 'base64').toString('utf8');
  const separator = decoded.indexOf(':');
  if (separator < 0 || !checkCredentials(decoded.slice(0, separator), decoded.slice(separator + 1))) {
    return false;
  }
  if (acceptedHeaders.size >= 20) {
    acceptedHeaders.clear();
  }
  acceptedHeaders.add(key);
  return true;
}

// Helper for the function nodes: global.get('gladys').trigger('door_opened', { value: 1 })
const gladys = {
  eventUrl: GLADYS_EVENT_URL,
  trigger: async function trigger(event, data) {
    const body = Object.assign({}, data || {}, { event: event });
    const response = await fetch(GLADYS_EVENT_URL, {
      method: 'POST',
      headers: { 'content-type': 'application/json', authorization: 'Bearer ' + GLADYS_EVENT_TOKEN },
      body: JSON.stringify(body),
      signal: AbortSignal.timeout(10000),
    });
    const result = await response.json().catch(function () {
      return {};
    });
    if (!response.ok) {
      throw new Error('Gladys refused the event (HTTP ' + response.status + '): ' + (result.error || ''));
    }
    return result;
  },
};

const user = { username: ADMIN_USERNAME, permissions: '*' };

module.exports = {
  flowFile: 'flows.json',
  flowFilePretty: true,
  credentialSecret: CREDENTIAL_SECRET,

  uiPort: process.env.PORT || 1880,

  adminAuth: {
    type: 'credentials',
    users: function (username) {
      return Promise.resolve(username === ADMIN_USERNAME ? user : null);
    },
    authenticate: function (username, password) {
      return Promise.resolve(checkCredentials(username, password) ? user : null);
    },
  },

  httpNodeMiddleware: function (req, res, next) {
    if (!PROTECT_HTTP_NODES || checkBasicHeader(req.headers.authorization)) {
      return next();
    }
    res.set('WWW-Authenticate', 'Basic realm="Node-RED", charset="UTF-8"');
    res.status(401).send('Unauthorized');
  },

  functionGlobalContext: { gladys: gladys },
  functionExternalModules: true,
  exportGlobalContextKeys: false,

  contextStorage: PERSIST_CONTEXT
    ? { default: { module: 'localfilesystem' }, memory: { module: 'memory' } }
    : { default: { module: 'memory' } },

  runtimeState: { enabled: true, ui: true },
  diagnostics: { enabled: true, ui: true },

  logging: {
    console: { level: 'info', metrics: false, audit: false },
  },

  editorTheme: {
    page: { title: 'Node-RED · Gladys' },
    header: { title: 'Node-RED · Gladys' },
    projects: { enabled: false },
    palette: {},
  },

  debugMaxLength: 1000,
  mqttReconnectTime: 15000,
  serialReconnectTime: 15000,
};
`;
